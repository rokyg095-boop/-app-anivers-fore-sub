function generateSeasonEpisodes(
  startNum: number,
  endNum: number,
  seasonPrefix: string,
  seasonArabicName: string
): DubEpisode[] {
  const eps: DubEpisode[] = [];
  for (let i = startNum; i <= endNum; i++) {
    const padNum = i.toString().padStart(2, '0');
    const famous = FAMOUS_NARUTO_TITLES[i];
    const title = famous ? famous.title : `الحلقة ${padNum}: مغامرة الشينوبي في ${seasonArabicName}`;
    const desc = famous
      ? famous.desc
      : `حلقة كاملة من ${seasonArabicName}: يخوض ناروتو ورفاقه من شينوبي كونوها تحديات قتالية ومهاماً مصيرية لحماية أصدقائهم وتحقيق أحلامهم (جاهزة للربط برابط درايف المباشر).`;

    eps.push({
      id: `naruto-${seasonPrefix}-ep${i}`,
      episodeNumber: i,
      title,
      duration: '23:30',
      thumbnail: NARUTO_IMAGE,
      videoUrl: '',
      dubStudio: NARUTO_STUDIO,
      voiceActors: NARUTO_VOICES,
      releaseDate: 'جاهزة للربط عبر درايف',
      description: desc,
      isComingSoon: true,
    });
  }
  return eps;
}

